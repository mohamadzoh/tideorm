use proc_macro2::{Ident, TokenStream};
use quote::{ToTokens, quote};
use syn::ext::IdentExt;

use super::EngineField;

/// The model's columns: their fields, `Column` variants and the types they
/// hold, an encrypted column's payload text.
struct DeriveActiveModel<'a> {
    model: &'a Ident,
    fields: Vec<&'a Ident>,
    names: Vec<&'a Ident>,
    types: Vec<TokenStream>,
    /// `From<Model>`'s value per column: an encrypted one is left unset, its
    /// payload only `InternalModel::try_into_active_model` can seal.
    from_model: Vec<TokenStream>,
}

impl DeriveActiveModel<'_> {
    fn define_active_model(&self, vis: &TokenStream) -> TokenStream {
        let fields = &self.fields;
        let types = &self.types;
        quote!(
            #[doc = " Generated by tideorm-macros"]
            #[derive(Clone, Debug, PartialEq)]
            #vis struct ActiveModel {
                #(
                    #[doc = " Generated by tideorm-macros"]
                    pub #fields: ::tideorm::orm::ActiveValue<#types>
                ),*
            }
        )
    }

    fn impl_active_model(&self) -> TokenStream {
        let mut ts = self.impl_active_model_convert();
        ts.extend(self.impl_active_model_trait());
        ts
    }

    fn impl_active_model_convert(&self) -> TokenStream {
        let model = &self.model;
        let fields = &self.fields;
        let from_model = &self.from_model;

        quote!(
            #[automatically_derived]
            impl std::default::Default for ActiveModel {
                fn default() -> Self {
                    <Self as ::tideorm::orm::ActiveModelTrait>::default()
                }
            }

            #[automatically_derived]
            impl std::convert::From<#model> for ActiveModel {
                fn from(m: #model) -> Self {
                    Self {
                        #(#fields: #from_model),*
                    }
                }
            }

            #[automatically_derived]
            impl ::tideorm::orm::IntoActiveModel<ActiveModel> for #model {
                fn into_active_model(self) -> ActiveModel {
                    self.into()
                }
            }
        )
    }

    fn impl_active_model_trait(&self) -> TokenStream {
        let fields = &self.fields;
        let methods = self.impl_active_model_trait_methods();

        quote! {
            #[automatically_derived]
            impl ::tideorm::orm::ActiveModelTrait for ActiveModel {
                type Entity = Entity;

                #methods

                fn default() -> Self {
                    Self {
                        #(#fields: ::tideorm::orm::ActiveValue::NotSet),*
                    }
                }
            }
        }
    }

    pub fn impl_active_model_trait_methods(&self) -> TokenStream {
        let fields = &self.fields;
        let names = &self.names;

        quote!(
            fn take(&mut self, c: <Self::Entity as ::tideorm::orm::EntityTrait>::Column) -> ::tideorm::orm::ActiveValue<::tideorm::orm::Value> {
                match c {
                    #(<Self::Entity as ::tideorm::orm::EntityTrait>::Column::#names => {
                        let mut value = ::tideorm::orm::ActiveValue::NotSet;
                        std::mem::swap(&mut value, &mut self.#fields);
                        value.into_wrapped_value()
                    },)*
                    _ => ::tideorm::orm::ActiveValue::NotSet,
                }
            }

            fn get(&self, c: <Self::Entity as ::tideorm::orm::EntityTrait>::Column) -> ::tideorm::orm::ActiveValue<::tideorm::orm::Value> {
                match c {
                    #(<Self::Entity as ::tideorm::orm::EntityTrait>::Column::#names => self.#fields.clone().into_wrapped_value(),)*
                    _ => ::tideorm::orm::ActiveValue::NotSet,
                }
            }

            fn set_if_not_equals(&mut self, c: <Self::Entity as ::tideorm::orm::EntityTrait>::Column, v: ::tideorm::orm::Value) {
                match c {
                    #(<Self::Entity as ::tideorm::orm::EntityTrait>::Column::#names => self.#fields.set_if_not_equals(v.unwrap()),)*
                    _ => (),
                }
            }

            fn try_set(&mut self, c: <Self::Entity as ::tideorm::orm::EntityTrait>::Column, v: ::tideorm::orm::Value) -> ::core::result::Result<(), ::tideorm::orm::DbErr> {
                match c {
                    #(<Self::Entity as ::tideorm::orm::EntityTrait>::Column::#names => self.#fields = ::tideorm::orm::ActiveValue::Set(::tideorm::orm::sql_builder::ValueType::try_from(v).map_err(|e| ::tideorm::orm::DbErr::Type(e.to_string()))?),)*
                    _ => return Err(::tideorm::orm::DbErr::Type(format!("ActiveModel does not have this field: {:?}", ::tideorm::orm::ColumnTrait::as_column_ref(&c)))),
                }
                Ok(())
            }

            fn not_set(&mut self, c: <Self::Entity as ::tideorm::orm::EntityTrait>::Column) {
                match c {
                    #(<Self::Entity as ::tideorm::orm::EntityTrait>::Column::#names => self.#fields = ::tideorm::orm::ActiveValue::NotSet,)*
                    _ => (),
                }
            }

            fn is_not_set(&self, c: <Self::Entity as ::tideorm::orm::EntityTrait>::Column) -> bool {
                match c {
                    #(<Self::Entity as ::tideorm::orm::EntityTrait>::Column::#names => self.#fields.is_not_set(),)*
                    _ => panic!("This ActiveModel does not have this field"),
                }
            }

            fn reset(&mut self, c: <Self::Entity as ::tideorm::orm::EntityTrait>::Column) {
                match c {
                    #(<Self::Entity as ::tideorm::orm::EntityTrait>::Column::#names => self.#fields.reset(),)*
                    _ => panic!("This ActiveModel does not have this field"),
                }
            }

            fn default_values() -> Self {
                use ::tideorm::orm::value::{DefaultActiveValue, DefaultActiveValueNone, DefaultActiveValueNotSet};
                let mut default = <Self as ::tideorm::orm::ActiveModelTrait>::default();
                #(default.#fields = (&default.#fields).default_value();)*
                default
            }
        )
    }
}

fn derive_into_model(model: &Ident, fields: &[EngineField]) -> TokenStream {
    let columns: Vec<&Ident> = fields
        .iter()
        .filter(|field| field.column.is_some())
        .map(|field| field.ident)
        .collect();
    let model_fields = fields.iter().map(|field| field.ident);
    let model_values = fields.iter().map(|field| {
        let ident = field.ident;
        match field.column {
            Some(variant) if field.encrypted => {
                let field_name = ident.unraw().to_string();
                quote!(::tideorm::model::__decrypt_model_field::<Self, _>(
                    a.#ident.unwrap(),
                    #field_name,
                    ::tideorm::orm::IdenStatic::as_str(
                        &<<Self as ::tideorm::orm::ModelTrait>::Entity as ::tideorm::orm::EntityTrait>::Column::#variant,
                    ),
                )?)
            }
            Some(_) => quote!(a.#ident.unwrap()),
            None => quote!(Default::default()),
        }
    });

    quote!(
        #[automatically_derived]
        impl std::convert::TryFrom<ActiveModel> for #model {
            type Error = ::tideorm::orm::DbErr;
            fn try_from(a: ActiveModel) -> ::core::result::Result<Self, ::tideorm::orm::DbErr> {
                #(if a.#columns.is_not_set() {
                    return Err(::tideorm::orm::DbErr::AttrNotSet(stringify!(#columns).to_owned()));
                })*
                Ok(
                    Self {
                        #(#model_fields: #model_values),*
                    }
                )
            }
        }

        #[automatically_derived]
        impl ::tideorm::orm::TryIntoModel<#model> for ActiveModel {
            fn try_into_model(self) -> ::core::result::Result<#model, ::tideorm::orm::DbErr> {
                self.try_into()
            }
        }
    )
}

/// The `ActiveModel` struct, declared with `vis`, and apart from it the impls
/// converting between it and the model, which name the model and so go
/// beside it.
pub(crate) fn expand_active_model(
    vis: &TokenStream,
    model: &Ident,
    fields: &[EngineField],
) -> (TokenStream, TokenStream) {
    let columns = || fields.iter().filter(|field| field.column.is_some());
    let active_model = DeriveActiveModel {
        model,
        fields: columns().map(|field| field.ident).collect(),
        names: columns().filter_map(|field| field.column).collect(),
        types: columns()
            .map(|field| {
                if field.encrypted {
                    quote!(::core::option::Option<::std::string::String>)
                } else {
                    field.ty.to_token_stream()
                }
            })
            .collect(),
        from_model: columns()
            .map(|field| {
                let ident = field.ident;
                if field.encrypted {
                    quote!(::tideorm::orm::ActiveValue::NotSet)
                } else {
                    quote!(::tideorm::orm::ActiveValue::Unchanged(m.#ident))
                }
            })
            .collect(),
    };
    let mut impls = active_model.impl_active_model();
    impls.extend(derive_into_model(model, fields));
    (active_model.define_active_model(vis), impls)
}
