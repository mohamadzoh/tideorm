//! PostgreSQL's catalog statements, on `pg_catalog`.

use super::Queries;

/// The user objects of the catalog `$catalog` (aliased `$alias`) that
/// `$condition` keeps, as `name`: bare in the current schema, `schema.name`
/// elsewhere. PostgreSQL's own schemas and what an extension installed are
/// left out.
macro_rules! user_objects {
    ($catalog:literal, $alias:literal, $name:literal, $namespace:literal, $condition:literal) => {
        concat!(
            "SELECT (CASE WHEN n.nspname = current_schema() THEN ",
            $alias,
            ".",
            $name,
            " ELSE n.nspname || '.' || ",
            $alias,
            ".",
            $name,
            " END)::text AS name",
            " FROM ",
            $catalog,
            " ",
            $alias,
            " JOIN pg_namespace n ON n.oid = ",
            $alias,
            ".",
            $namespace,
            " WHERE ",
            $condition,
            " AND n.nspname <> 'information_schema' AND left(n.nspname, 3) <> 'pg_'",
            " AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = '",
            $catalog,
            "'::regclass AND d.objid = ",
            $alias,
            ".oid AND d.deptype = 'e')",
            " ORDER BY n.nspname, ",
            $alias,
            ".",
            $name
        )
    };
}

pub(super) const QUERIES: Queries = Queries {
    tables: user_objects!(
        "pg_class",
        "c",
        "relname",
        "relnamespace",
        "c.relkind IN ('r', 'p')"
    ),
    views: user_objects!(
        "pg_class",
        "c",
        "relname",
        "relnamespace",
        "c.relkind = 'v'"
    ),
    sequences: Some(user_objects!(
        "pg_class",
        "c",
        "relname",
        "relnamespace",
        "c.relkind = 'S'"
    )),
    enum_types: Some(user_objects!(
        "pg_type",
        "t",
        "typname",
        "typnamespace",
        "t.typtype = 'e'"
    )),
    table_exists: "SELECT EXISTS (SELECT FROM information_schema.tables \
                   WHERE table_schema = COALESCE($1, current_schema()) AND table_name = $2) AS present",
    columns: "SELECT a.attname::text AS name, format_type(a.atttypid, a.atttypmod) AS data_type, \
              NOT a.attnotnull AS nullable, \
              CASE WHEN a.attgenerated = '' THEN pg_get_expr(ad.adbin, ad.adrelid) END AS default_value, \
              EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid = a.attrelid AND k.contype = 'p' \
                      AND a.attnum = ANY (k.conkey)) AS primary_key, \
              CASE WHEN a.attidentity = 'a' THEN 'GENERATED ALWAYS AS IDENTITY' \
                   WHEN a.attidentity = 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY' \
                   WHEN a.attgenerated = 's' THEN 'GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED' \
                   WHEN a.attgenerated = 'v' THEN 'GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') VIRTUAL' \
              END AS extra \
              FROM pg_attribute a \
              JOIN pg_class c ON c.oid = a.attrelid AND c.relkind IN ('r', 'p', 'v', 'm', 'f') \
              JOIN pg_namespace n ON n.oid = c.relnamespace \
              LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum \
              WHERE n.nspname = COALESCE($1, current_schema()) AND c.relname = $2 \
                AND a.attnum > 0 AND NOT a.attisdropped \
              ORDER BY a.attnum",
    // An expression key has no attribute (`indkey` holds 0 for it), so it
    // is written as its expression.
    indexes: "SELECT i.relname::text AS name, \
              COALESCE(a.attname::text, pg_get_indexdef(x.indexrelid, k, true)) AS column_name, \
              x.indisunique AS is_unique, x.indisprimary AS is_primary, \
              a.attname IS NOT NULL AS whole_column \
              FROM pg_index x \
              JOIN pg_class t ON t.oid = x.indrelid \
              JOIN pg_namespace n ON n.oid = t.relnamespace \
              JOIN pg_class i ON i.oid = x.indexrelid \
              CROSS JOIN LATERAL generate_series(1, x.indnkeyatts::int) AS k \
              LEFT JOIN pg_attribute a ON a.attrelid = x.indrelid AND a.attnum = x.indkey[k - 1] \
              WHERE n.nspname = COALESCE($1, current_schema()) AND t.relname = $2 \
              ORDER BY i.relname, k",
    foreign_keys: "SELECT a.attname::text AS column_name, \
                   (CASE WHEN rn.nspname = current_schema() THEN r.relname \
                         ELSE rn.nspname || '.' || r.relname END)::text AS references_table, \
                   ra.attname::text AS references_column \
                   FROM pg_constraint k \
                   JOIN pg_class t ON t.oid = k.conrelid \
                   JOIN pg_namespace n ON n.oid = t.relnamespace \
                   JOIN pg_class r ON r.oid = k.confrelid \
                   JOIN pg_namespace rn ON rn.oid = r.relnamespace \
                   CROSS JOIN LATERAL unnest(k.conkey, k.confkey) WITH ORDINALITY AS u(attnum, refnum, ord) \
                   JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = u.attnum \
                   JOIN pg_attribute ra ON ra.attrelid = k.confrelid AND ra.attnum = u.refnum \
                   WHERE k.contype = 'f' AND n.nspname = COALESCE($1, current_schema()) AND t.relname = $2 \
                   ORDER BY k.conname, u.ord",
    index_table: Some(
        "SELECT tablename::text AS name FROM pg_indexes \
         WHERE schemaname = COALESCE($1, current_schema()) AND indexname = $2",
    ),
};
